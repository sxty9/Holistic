// Package catalogue is the single answer to "which apps does this instance
// publish", and the three files that answer has to reach.
//
// This is the reason Holistic exists as a component rather than a folder. One
// decision by one person fans out into three configurations owned by three
// different programs:
//
//	Warpgate   apps[]                  -> a DNS record and an ingress rule
//	coreX      instance.appOrigins     -> what /api/instance advertises, and
//	                                      therefore which apps the launcher offers
//	Solisuite  apps[] with host+origin -> the Host -> app map appFor() needs
//
// None of the three can see the other two. The Solisuite half is generated by
// nothing at all today, and appFor() is inert without it — so the practical
// state of the landscape before this package was that publishing an app meant
// editing three files by hand and finding out you had missed one when a
// hostname served the wrong document.
//
// Nothing here contains a domain. Hostnames are derived from one that is passed
// in, which is the rule the whole landscape is built on: the instance's domain
// exists in exactly one file on one machine.
package catalogue

import (
	"errors"
	"fmt"
	"sort"
	"strings"
)

// App is one thing the instance publishes at <id>.<domain>.
type App struct {
	// ID is the subdomain label and the identity everything else keys on.
	ID string `json:"id"`
	// Label is what a person sees in the launcher.
	Label string `json:"label"`
	Icon  string `json:"icon,omitempty"`
	// Upstream is the internal address traffic is handed to. Never public.
	Upstream string `json:"upstream"`
	// Enabled is the checkbox in the wizard.
	Enabled bool `json:"enabled"`
	// Protocols this route must carry beyond plain HTTP. Only "sse" changes
	// anything today; the rest are recorded and inert, and are marked as such
	// rather than left to read as promises.
	Protocols []string `json:"protocols,omitempty"`
	// Standalone marks an app that is not served by Solisuite — RoomSense has
	// its own server. It still needs DNS and ingress, and must NOT appear in
	// Solisuite's app list, where it would map a Host to a document that does
	// not exist.
	Standalone bool `json:"standalone,omitempty"`
	// Required marks an app the instance does not work without. The wizard
	// shows these as checked and refuses to uncheck them, rather than letting
	// somebody build an instance with no way to sign in.
	Required bool `json:"required,omitempty"`
	// Note is shown next to the checkbox.
	Note string `json:"note,omitempty"`
}

// Default is the catalogue a fresh instance starts from. It is a function
// rather than a package variable so that a caller cannot mutate the defaults
// for everybody else — the wizard hands this straight to a UI that edits it.
