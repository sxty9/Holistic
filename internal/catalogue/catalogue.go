// The upstreams are the ports the units in this landscape bind. They are
// internal addresses, not instance configuration, which is why they are
// constants here and the domain never is.
const (
	solisuite = "http://127.0.0.1:8795"
	roomsense = "http://127.0.0.1:8797"
	routedge  = "http://127.0.0.1:8793"
)

// Catalogue is the decision, plus the domain it is expressed under.
type Catalogue struct {
	Domain string
	Apps   []App
}

func New(domain string, apps []App) Catalogue {
	return Catalogue{Domain: strings.TrimSpace(strings.ToLower(domain)), Apps: apps}
}

var (
	ErrNoDomain   = errors.New("the catalogue has no domain, so no hostname can be derived")
	ErrNoLauncher = errors.New("the launcher is disabled, which would leave no way in")
)

// Validate refuses catalogues that would produce a broken instance.
func (c Catalogue) Validate() error {
	if c.Domain == "" {
		return ErrNoDomain
	}
	if strings.ContainsAny(c.Domain, "/: ") {
		return fmt.Errorf("%q is not a bare domain", c.Domain)
	}
	seen := map[string]bool{}
	launcher := false
	for _, a := range c.Apps {
		if a.ID == "" {
			return errors.New("every app needs an id — it becomes the subdomain")
		}
		if seen[a.ID] {
			return fmt.Errorf("app %q appears twice", a.ID)
		}
		seen[a.ID] = true
		if a.Enabled && a.Upstream == "" {
			return fmt.Errorf("app %q is enabled with no upstream", a.ID)
		}
		if a.Required && !a.Enabled {
			return fmt.Errorf("app %q cannot be disabled", a.ID)
		}
		if a.ID == "launcher" && a.Enabled {
			launcher = true
		}
	}
	if !launcher {
		return ErrNoLauncher
	}
	return nil
}

// Hostname is where an app answers. The one place a hostname is composed.
func (c Catalogue) Hostname(id string) string { return id + "." + c.Domain }

// Origin is the URL other components record for an app. https, always: the
// only way in from outside is the tunnel, and the tunnel terminates TLS.
func (c Catalogue) Origin(id string) string { return "https://" + c.Hostname(id) }

// Enabled returns the chosen apps, in a stable order.
func (c Catalogue) Enabled() []App {
	var out []App
	for _, a := range c.Apps {
		if a.Enabled {
			out = append(out, a)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out
}

// --- the three projections -------------------------------------------------

// WarpgateApp mirrors Warpgate's config.App. It is duplicated rather than
// imported: Holistic writes a JSON file that Warpgate reads, and a shared Go
// type would make one repository's refactor break another's file format
// silently. The file is the contract.
type WarpgateApp struct {
	Name      string   `json:"name"`
	Upstream  string   `json:"upstream"`
	Protocols []string `json:"protocols,omitempty"`
	Comment   string   `json:"comment,omitempty"`
}

// Warpgate is what becomes DNS and ingress.
func (c Catalogue) Warpgate() []WarpgateApp {
	var out []WarpgateApp
	for _, a := range c.Enabled() {
		w := WarpgateApp{Name: a.ID, Upstream: a.Upstream, Protocols: a.Protocols, Comment: a.Note}
		out = append(out, w)
	}
	return out
}

// SolisuiteApp mirrors Solisuite's server config.
type SolisuiteApp struct {
	ID     string `json:"id"`
	Label  string `json:"label"`
	Icon   string `json:"icon,omitempty"`
	Host   string `json:"host"`
	Origin string `json:"origin"`
}

// Solisuite is the Host -> app map appFor() needs, and which nothing generated
// before. Standalone apps are excluded: RoomSense has its own server, and
// listing it here would map its hostname to a Solisuite document that does not
// exist.
func (c Catalogue) Solisuite() []SolisuiteApp {
	var out []SolisuiteApp
	for _, a := range c.Enabled() {
		if a.Standalone {
			continue
		}
		out = append(out, SolisuiteApp{
			ID: a.ID, Label: a.Label, Icon: a.Icon,
			Host: c.Hostname(a.ID), Origin: c.Origin(a.ID),
		})
	}
	return out
}

// CoreXOrigins is what /api/instance advertises, and therefore which apps the
// launcher offers.
//
// proven is the set of app ids whose hostname has actually answered a probe
// from the public internet. Apps are added as they are proven rather than all
// at once, for a reason worth keeping: an origin map listing eight hostnames
// that do not resolve is the populated-but-wrong state that shipped once
// already, and writing it incrementally turns the launcher into an honest
// progress display for free — shellApps() already filters to apps that have an
// origin.
//
// Passing nil means "none proven yet" and yields an empty map, not every app.
func (c Catalogue) CoreXOrigins(proven map[string]bool) map[string]string {
	out := map[string]string{}
	for _, a := range c.Enabled() {
		if a.Standalone {
			// coreX serves no API for it and the launcher cannot open it as
			// one of its own.
			continue
		}
		if proven[a.ID] {
			out[a.ID] = c.Origin(a.ID)
		}
	}
	return out
}

// Hostnames is every name that has to resolve for this catalogue to be true —
// the list the wizard probes, one nonce request each.
func (c Catalogue) Hostnames() []string {
	var out []string
	for _, a := range c.Enabled() {
		out = append(out, c.Hostname(a.ID))
	}
	return out
}
